package com.coralblocks.coralproto;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import org.junit.Assert;
import org.junit.Test;

public class IDLTest {

	@Test
	public void testGeneratesDirectSerializationMethods() {
		IDL idl = new IDL("""
				TYPE = T
				SUBTYPE = D
				VERSION = 7

				required: long
				optional: int!
				entries:
					price: double
					quantity: int
				""");

		String code = idl.getCode();
		Assert.assertTrue(code.contains("public final int getLength()"));
		Assert.assertTrue(code.contains("+ required.size()"));
		Assert.assertTrue(code.contains("+ optional.size()"));
		Assert.assertTrue(code.contains("+ entries.size()"));
		Assert.assertTrue(code.contains("required.readFrom(buf);"));
		Assert.assertTrue(code.contains("required.reset();"));
		Assert.assertTrue(code.contains("optional.markAsNotPresent();"));
		Assert.assertTrue(code.contains("if (optional.isPresent())"));
		Assert.assertTrue(code.contains("entries.readFrom(buf);"));
		Assert.assertTrue(code.contains("buf.putShort((short) 7);"));
		Assert.assertTrue(code.contains("public final void writeAscii(boolean shortVersion, java.nio.ByteBuffer buf)"));
		Assert.assertTrue(code.contains("writeAsciiTypeSubtypeVersionName(shortVersion, buf);"));
		Assert.assertTrue(code.contains("required.writeAsciiTo(buf);"));
		Assert.assertTrue(code.contains("optional.writeAsciiTo(buf);"));
		Assert.assertTrue(code.contains("writeAscii(buf, \"BLANK\");"));
	}

	@Test
	public void testRejectsEmptyRepeatingGroup() {
		IllegalArgumentException e = Assert.assertThrows(IllegalArgumentException.class, () -> new IDL("""
				TYPE = E
				SUBTYPE = G
				orders:
				"""));

		Assert.assertEquals("Repeating group 'orders' must contain at least one indented field", e.getMessage());
	}

	@Test
	public void testReplaceAutoGeneratedCode() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Message.java");
		Path temp = Path.of(target + ".tmp");
		try {
			Files.writeString(target, "package example;\n\n// BEGIN_AUTO_GENERATED_CODE\nold code\n// END_AUTO_GENERATED_CODE\nafter\n");
			IDL idl = new IDL("""
					TYPE = I
					SUBTYPE = M
					side: charEnum(com.example.Side)
					""");

			idl.replaceAutoGeneratedCode(target.toString());

			String replaced = Files.readString(target);
			Assert.assertTrue(replaced.contains("import com.coralblocks.coralproto.AbstractProto;"));
			Assert.assertTrue(replaced.contains("import com.coralblocks.coralproto.field.*;"));
			Assert.assertTrue(replaced.contains("import com.example.Side;"));
			Assert.assertTrue(replaced.contains("CharEnumField<Side> side"));
			Assert.assertTrue(replaced.contains("after"));
			Assert.assertFalse(replaced.contains("old code"));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}

	@Test
	public void testMissingEndMarkerLeavesSourceUntouched() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Message.java");
		Path temp = Path.of(target + ".tmp");
		String original = "package example;\n\n// BEGIN_AUTO_GENERATED_CODE\nold code\n";
		try {
			Files.writeString(target, original);
			IDL idl = new IDL("TYPE = I\nSUBTYPE = M\nvalue: int");

			IOException e = Assert.assertThrows(IOException.class,
					() -> idl.replaceAutoGeneratedCode(target.toString()));

			Assert.assertTrue(e.getMessage().contains("Cannot find END_AUTO_GENERATED_CODE"));
			Assert.assertEquals(original, Files.readString(target));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}

	@Test
	public void testWriteJavaClassReplacesExistingFile() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Generated.java");
		Path temp = Path.of(target + ".tmp");
		try {
			Files.writeString(target, "original");
			new IDL("TYPE = I\nSUBTYPE = M\nside: charEnum(com.example.Side)");
			IDL idl = new IDL("TYPE = I\nSUBTYPE = M\nvalue: int");

			idl.writeJavaClass(temp.toString(), "example", "Generated");

			String generated = Files.readString(target);
			Assert.assertTrue(generated.contains("package example;"));
			Assert.assertTrue(generated.contains("IntField value"));
			Assert.assertFalse(generated.contains("com.example.Side"));
			Assert.assertFalse(generated.contains("original"));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}

	@Test
	public void testCommandUsesProvidedFolder() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path nestedDirectory = Files.createDirectory(directory.resolve("idl"));
		Path schema = directory.resolve("Message.idl");
		Path ignored = directory.resolve("Ignore.txt");
		Path nestedSchema = nestedDirectory.resolve("Nested.idl");
		Path generated = directory.resolve("Message.java.tmp");
		try {
			Files.writeString(schema, "CLASSNAME = example.Message\nTYPE = M\nSUBTYPE = S\nvalue: int\n");
			Files.writeString(ignored, "not a schema");
			Files.writeString(nestedSchema, "CLASSNAME = example.Nested\nTYPE = N\nSUBTYPE = S\nvalue: int\n");

			List<File> files = IDL.findAllFiles(directory.toString(), ".idl");
			Assert.assertEquals(1, files.size());
			Assert.assertEquals(schema.toFile(), files.get(0));

			IDL.main(new String[] { directory.toString(), "true", "idl" });
			Assert.assertTrue(Files.exists(generated));
			Assert.assertFalse(Files.exists(nestedDirectory.resolve("Nested.java.tmp")));
		} finally {
			Files.deleteIfExists(generated);
			Files.deleteIfExists(nestedSchema);
			Files.deleteIfExists(nestedDirectory);
			Files.deleteIfExists(ignored);
			Files.deleteIfExists(schema);
			Files.deleteIfExists(directory);
		}
	}
}
