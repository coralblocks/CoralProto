package com.coralblocks.coralproto;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.Assert;
import org.junit.Test;

public class IDLTest {

	@Test
	public void testGeneratesDirectSerializationMethods() {
		IDL idl = new IDL("""
				TYPE = T
				SUBTYPE = D
				VERSION = 7

				required: long
				optional: int!
				entries:
					price: double
					quantity: int
				""");

		String code = idl.getCode();
		Assert.assertTrue(code.contains("public final int getLength()"));
		Assert.assertTrue(code.contains("+ required.size()"));
		Assert.assertTrue(code.contains("+ optional.size()"));
		Assert.assertTrue(code.contains("+ entries.size()"));
		Assert.assertTrue(code.contains("required.readFrom(buf);"));
		Assert.assertTrue(code.contains("required.reset();"));
		Assert.assertTrue(code.contains("optional.markAsNotPresent();"));
		Assert.assertTrue(code.contains("if (optional.isPresent())"));
		Assert.assertTrue(code.contains("entries.readFrom(buf);"));
		Assert.assertTrue(code.contains("buf.putShort((short) 7);"));
		Assert.assertTrue(code.contains("public final void writeAscii(boolean shortVersion, java.nio.ByteBuffer buf)"));
		Assert.assertTrue(code.contains("writeAsciiTypeSubtypeVersionName(shortVersion, buf);"));
		Assert.assertTrue(code.contains("required.writeAsciiTo(buf);"));
		Assert.assertTrue(code.contains("optional.writeAsciiTo(buf);"));
		Assert.assertTrue(code.contains("writeAscii(buf, \"BLANK\");"));
	}

	@Test
	public void testReplaceAutoGeneratedCode() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Message.java");
		Path temp = Path.of(target + ".tmp");
		try {
			Files.writeString(target, "before\n// BEGIN_AUTO_GENERATED_CODE\nold code\n// END_AUTO_GENERATED_CODE\nafter\n");

			IDL.replaceAutoGeneratedCode(target.toString(), "new code");

			String replaced = Files.readString(target);
			Assert.assertTrue(replaced.contains("before"));
			Assert.assertTrue(replaced.contains("new code"));
			Assert.assertTrue(replaced.contains("after"));
			Assert.assertFalse(replaced.contains("old code"));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}

	@Test
	public void testMissingEndMarkerLeavesSourceUntouched() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Message.java");
		Path temp = Path.of(target + ".tmp");
		String original = "before\n// BEGIN_AUTO_GENERATED_CODE\nold code\n";
		try {
			Files.writeString(target, original);

			IOException e = Assert.assertThrows(IOException.class,
					() -> IDL.replaceAutoGeneratedCode(target.toString(), "new code"));

			Assert.assertTrue(e.getMessage().contains("Cannot find END_AUTO_GENERATED_CODE"));
			Assert.assertEquals(original, Files.readString(target));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}

	@Test
	public void testWriteJavaClassReplacesExistingFile() throws IOException {
		Path directory = Files.createTempDirectory("coralproto-idl-");
		Path target = directory.resolve("Generated.java");
		Path temp = Path.of(target + ".tmp");
		try {
			Files.writeString(target, "original");

			IDL.writeJavaClass(temp.toString(), "generated field", "example", "Generated");

			String generated = Files.readString(target);
			Assert.assertTrue(generated.contains("package example;"));
			Assert.assertTrue(generated.contains("generated field"));
			Assert.assertFalse(generated.contains("original"));
			Assert.assertFalse(Files.exists(temp));
		} finally {
			Files.deleteIfExists(temp);
			Files.deleteIfExists(target);
			Files.deleteIfExists(directory);
		}
	}
}
